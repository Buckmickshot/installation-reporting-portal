-- ---------- installation: new columns ---------------------------------------
alter table snapshot.installation
  add column job_number    bigint generated by default as identity,
  add column status        text not null default 'draft',
  add column assigned_to   uuid references snapshot.profiles(user_id) on delete set null,
  add column form_data     jsonb not null default '{}'::jsonb,
  add column installation_date date,
  add column submitted_at  timestamptz,
  add column approved_at   timestamptz;

alter table snapshot.installation
  add constraint installation_status_check check (status in
    ('draft','ready_for_review','rfi','submitted','approved','paid','cancelled'));
create unique index on snapshot.installation (job_number);
create index on snapshot.installation (company_id, status);
create index on snapshot.installation (assigned_to);

-- ---------- audit trail / notes / RFIs ---------------------------------------
create table snapshot.job_events (
  event_id        uuid primary key default gen_random_uuid(),
  installation_id uuid not null references snapshot.installation(installation_id) on delete cascade,
  company_id      uuid not null references snapshot.companies(company_id),
  actor           uuid default auth.uid() references auth.users(id) on delete set null,
  event_type      text not null check (event_type in ('created','status_change','assignment','note','rfi','evidence','saved')),
  from_status     text,
  to_status       text,
  message         text,
  created_at      timestamptz not null default now()
);
create index on snapshot.job_events (installation_id, created_at desc);

-- ---------- field evidence ---------------------------------------------------
create table snapshot.job_evidence (
  evidence_id     uuid primary key default gen_random_uuid(),
  installation_id uuid not null references snapshot.installation(installation_id) on delete cascade,
  company_id      uuid not null references snapshot.companies(company_id),
  kind            text not null check (kind in
                    ('old_unit','old_unit_nameplate','new_indoor_unit','new_outdoor_unit','new_unit_nameplate',
                     'decommissioned_unit','customer_signature','installer_signature','other')),
  file_url        text not null,
  file_name       text,
  product_index   int,
  note            text,
  latitude        double precision,
  longitude       double precision,
  accuracy_m      double precision,
  captured_at     timestamptz not null default now(),
  captured_by     uuid default auth.uid() references auth.users(id) on delete set null
);
create index on snapshot.job_evidence (installation_id);

create trigger trg_events_company before insert on snapshot.job_events
  for each row execute function snapshot.fill_company_from_installation();
create trigger trg_evidence_company before insert on snapshot.job_evidence
  for each row execute function snapshot.fill_company_from_installation();

alter table snapshot.job_events   enable row level security;
alter table snapshot.job_evidence enable row level security;
create policy job_events_read on snapshot.job_events for select to authenticated
  using (snapshot.can_access_company(company_id));
create policy job_events_note on snapshot.job_events for insert to authenticated
  with check (snapshot.can_access_company(company_id) and event_type in ('note','evidence') and actor = auth.uid());
create policy job_evidence_rw on snapshot.job_evidence for all to authenticated
  using (snapshot.can_access_company(company_id)) with check (snapshot.can_access_company(company_id));
grant select, insert on snapshot.job_events to authenticated;
grant select, insert, update, delete on snapshot.job_evidence to authenticated;
grant all on snapshot.job_events, snapshot.job_evidence to service_role;

-- ---------- automatic audit entries ------------------------------------------
create or replace function snapshot.installation_audit() returns trigger
language plpgsql security definer set search_path = snapshot, public as $$
begin
  if tg_op = 'INSERT' then
    insert into snapshot.job_events (installation_id, company_id, event_type, to_status, message)
      values (new.installation_id, new.company_id, 'created', new.status, 'Job created');
    return new;
  end if;
  if new.status is distinct from old.status then
    insert into snapshot.job_events (installation_id, company_id, event_type, from_status, to_status, message)
      values (new.installation_id, new.company_id, 'status_change', old.status, new.status,
              nullif(current_setting('snapshot.status_message', true), ''));
  end if;
  if new.assigned_to is distinct from old.assigned_to then
    insert into snapshot.job_events (installation_id, company_id, event_type, message)
      values (new.installation_id, new.company_id, 'assignment',
              coalesce('Assigned to ' || (select name from snapshot.profiles where user_id = new.assigned_to), 'Unassigned'));
  end if;
  return new;
end $$;
create trigger trg_installation_audit after insert or update of status, assigned_to on snapshot.installation
  for each row execute function snapshot.installation_audit();

-- status may only change through fn_set_job_status (which applies the rules)
create or replace function snapshot.installation_status_guard() returns trigger
language plpgsql as $$
begin
  if new.status is distinct from old.status
     and coalesce(current_setting('snapshot.via_status_rpc', true), '') <> 'on'
     and auth.uid() is not null then
    raise exception 'Use fn_set_job_status to change a job''s status' using errcode = '42501';
  end if;
  -- submitted jobs are locked for staff (admins can still correct them)
  if old.status in ('submitted','approved','paid')
     and coalesce(current_setting('snapshot.via_status_rpc', true), '') <> 'on'
     and auth.uid() is not null
     and not (snapshot.is_global_admin() or snapshot.is_company_admin(old.company_id))
     and (new.form_data is distinct from old.form_data or new.premises_id is distinct from old.premises_id
          or new.consumer_id is distinct from old.consumer_id) then
    raise exception 'This job has been submitted and is locked' using errcode = '42501';
  end if;
  return new;
end $$;
create trigger trg_installation_status_guard before update on snapshot.installation
  for each row execute function snapshot.installation_status_guard();

-- ---------- status transitions -----------------------------------------------
create or replace function snapshot.fn_set_job_status(_installation uuid, _status text, _message text default null)
returns snapshot.installation
language plpgsql security definer set search_path = snapshot, public as $$
declare
  r snapshot.installation;
  is_admin boolean;
  allowed boolean;
begin
  r := snapshot._assert_installation(_installation);
  is_admin := snapshot.is_global_admin() or snapshot.is_company_admin(r.company_id);

  allowed := case
    -- anyone in the company
    when r.status in ('draft','rfi') and _status = 'ready_for_review' then true
    when r.status = 'draft' and _status = 'cancelled' then true
    when r.status = 'ready_for_review' and _status = 'draft' then true      -- pull back to edit
    -- reviewers (company admin / global admin)
    when is_admin and r.status = 'ready_for_review' and _status in ('submitted','rfi') then true
    when is_admin and r.status = 'submitted' and _status in ('approved','rfi') then true
    when is_admin and r.status = 'approved' and _status = 'paid' then true
    when is_admin and r.status in ('ready_for_review','rfi','submitted') and _status = 'cancelled' then true
    when is_admin and r.status = 'cancelled' and _status = 'draft' then true
    else false
  end;

  if not allowed then
    raise exception 'Cannot move a job from % to %', r.status, _status using errcode = '42501';
  end if;
  if _status = 'rfi' and coalesce(trim(_message), '') = '' then
    raise exception 'A request for information needs a message';
  end if;

  perform set_config('snapshot.via_status_rpc', 'on', true);
  perform set_config('snapshot.status_message', coalesce(_message, ''), true);

  update snapshot.installation
     set status = _status,
         complete = _status in ('submitted','approved','paid'),
         submitted_at = case when _status = 'submitted' then now() else submitted_at end,
         approved_at  = case when _status = 'approved'  then now() else approved_at end
   where installation_id = _installation
  returning * into r;

  -- once submitted, the premises and customer become reusable "finished" records
  if _status = 'submitted' then
    update snapshot.premises set is_draft = false where premises_id = r.premises_id;
    update snapshot.consumer_details set is_draft = false where consumer_id = r.consumer_id;
  end if;

  perform set_config('snapshot.via_status_rpc', '', true);
  perform set_config('snapshot.status_message', '', true);
  return r;
end $$;

-- ---------- allocation -------------------------------------------------------
create or replace function snapshot.fn_assign_job(_installation uuid, _assignee uuid)
returns void language plpgsql security definer set search_path = snapshot, public as $$
declare r snapshot.installation;
begin
  r := snapshot._assert_installation(_installation);
  if not (snapshot.is_global_admin() or snapshot.is_company_admin(r.company_id)) then
    raise exception 'Only admins can allocate jobs' using errcode = '42501';
  end if;
  if _assignee is not null and not exists (
      select 1 from snapshot.profiles where user_id = _assignee and company_id = r.company_id and active) then
    raise exception 'Assignee must be an active user in the same company';
  end if;
  update snapshot.installation set assigned_to = _assignee where installation_id = _installation;
end $$;

-- ---------- delete a draft ---------------------------------------------------
create or replace function snapshot.fn_delete_installation(_installation uuid)
returns void language plpgsql security definer set search_path = snapshot, public as $$
declare r snapshot.installation;
begin
  r := snapshot._assert_installation(_installation);
  if r.status not in ('draft','cancelled') then
    raise exception 'Only draft or cancelled jobs can be deleted' using errcode = '42501';
  end if;
  if not (r.user_id = auth.uid() or snapshot.is_global_admin() or snapshot.is_company_admin(r.company_id)) then
    raise exception 'Only the creator or an admin can delete this job' using errcode = '42501';
  end if;
  delete from snapshot.installation where installation_id = _installation;
  delete from snapshot.premises p where p.premises_id = r.premises_id and p.is_draft
    and not exists (select 1 from snapshot.installation i where i.premises_id = p.premises_id);
  delete from snapshot.consumer_details c where c.consumer_id = r.consumer_id and c.is_draft
    and not exists (select 1 from snapshot.installation i where i.consumer_id = c.consumer_id);
end $$;

-- ---------- dashboard view ---------------------------------------------------
create or replace view snapshot.installation_overview
with (security_invoker = true) as
select
  i.installation_id,
  i.job_number,
  'VEU-' || lpad(i.job_number::text, 6, '0') as job_ref,
  i.company_id,
  cv.name                                   as company_name,
  i.activity_type,
  i.status,
  i.complete,
  i.created_at,
  i.updated_at,
  i.submitted_at,
  i.approved_at,
  i.installation_date,
  i.user_id,
  creator.name                              as created_by_name,
  i.assigned_to,
  assignee.name                             as assigned_to_name,
  p.premises_id,
  p.full_address,
  p.premises_type,
  c.consumer_id,
  nullif(trim(coalesce(c.first_name,'') || ' ' || coalesce(c.last_name,'')), '') as customer_name,
  c.phone_number                            as customer_phone,
  c.email_address                           as customer_email,
  coalesce(jsonb_array_length(nullif(i.form_data->'installedProducts', 'null'::jsonb)), 0) as product_count,
  (select count(*) from snapshot.job_evidence e where e.installation_id = i.installation_id) as evidence_count,
  (select e.message from snapshot.job_events e
     where e.installation_id = i.installation_id and e.to_status = 'rfi'
     order by e.created_at desc limit 1)    as last_rfi_message
from snapshot.installation i
left join snapshot.premises p          on p.premises_id = i.premises_id
left join snapshot.consumer_details c  on c.consumer_id = i.consumer_id
left join snapshot.profiles creator    on creator.user_id = i.user_id
left join snapshot.profiles assignee   on assignee.user_id = i.assigned_to
left join snapshot.current_company_versions cv on cv.company_id = i.company_id;

grant select on snapshot.installation_overview to authenticated;
grant execute on all functions in schema snapshot to authenticated;
